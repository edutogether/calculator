export const BUDGET = 1500000;
export const F = (n: number): string => n.toLocaleString('ko-KR');

/* 남는 돈을 부호와 함께 적는다 — **남으면 +, 넘치면 −, 딱 맞으면 부호 없음.**
   ⚠ 마이너스는 **예산을 넘겼을 때만** 붙인다(2026-09-09 대표 지시).
   한때 '남는 예산'에 −를 붙여 두었다가, 돈이 남는 정상 상태가 빨간 마이너스로 보여 정정했다.
   견적 합계와 협의회비 카드가 같은 규칙을 쓰도록 이 함수 하나만 쓴다.
   scripts/check-signs.js 가 세 경우(남음·딱 맞음·넘침)를 배포 전에 검사한다. */
export function signed(v: number): string { return (v > 0 ? '+' : v < 0 ? '−' : '') + F(Math.abs(v)) + '원'; }

/* 협의회비가 배정 예산에서 차지할 수 있는 최대 비율 — **40% 확정**(2026-09-09 대표 결정).
   ⚠ 이 비율은 **문서 근거를 찾지 못했다.** 2026학년도 학교회계 지침, 2026년도 교육비특별회계
   편성 기본지침, 2024년도 세출예산 집행지침을 모두 뒤져도 예산 대비 비율 조항이 없다.
   **대표님이 실무 기준으로 확정한 값이다.** 그래서 이 상한을 알리는 안내창에는
   법령 링크를 붙이지 않는다 — 근거 없는 링크는 없느니만 못하다.
   scripts/check-recommended.js 가 권장안이 이 상한을 지키는지 배포 전에 검사한다. */
export const MEET_MAX_RATIO = 0.40;

/* 집행률 색 구간 (2026-09-09 대표 확정).
   **예산을 많이 쓸수록 좋은 것**이고 적게 쓰면 경고다 — 거꾸로 읽지 말 것.
   색은 팔레트 토큰만 쓴다. 구간이 바뀌면 이 함수 안에서만 고친다.
   **화면에 보이는 값으로 판정한다.** 화면은 소수 1자리로 반올림해 보여 주므로,
   원값으로 판정하면 같은 '100.0%' 가 어떤 때는 빨강 어떤 때는 초록이 된다(실제로 그랬다).
   그리고 **정확히 100% 는 초록**이다 — 예산을 다 쓴 것은 최선이지 경고할 일이 아니다.
   빨강은 화면에 100.1% 이상이 찍힐 때부터다. */
export function rateClass(pct: number): string {
  const p = Number(pct.toFixed(1));
  if (p > 100) return ' r-over';     // 초과 — 빨강
  if (p >= 90) return ' r-good';     // 초록 (딱 100% 포함)
  if (p >= 70) return ' r-warn';     // 주황
  return ' r-low';                   // 70% 아래 — 흐린 회색(일부러 덜 보이게)
}

/* 인당 지원금액
   · 상한 40,000원 — 이것만 실제 제한이다. 넘겨 적으면 40,000원으로 맞춘다.
     금액의 출처는 「인천광역시 교육비특별회계 세출예산 집행지침」의 업무추진비(230목) 공통기준이고,
     학교가 따르는 것은 「(공립) 2026학년도 학교회계 예산편성 기본지침」이다.
     편성지침에는 금액이 없고 집행지침을 가리키므로 **안내창에 둘 다 건다** — 자세한 것은
     .claude/rules/app.md 참고.
     ⚠ 2024학년도 학교회계 지침에는 "1인당 3만원"이 적혀 있었지만, 2025학년도 개정에서 그 숫자를
     빼고 집행지침을 가리키도록 바뀌었다(개정 사유 "집행범위 일치"). **숫자의 출처가 옮겨간 것이다.**
     그래서 3만원이 아니라 4만원이 맞다 — 자세한 경위는 .claude/rules/app.md 참고.
   · 하한은 없다. 1만원 아래를 규칙으로 막지 않는다(현실적으로 잘 쓰지 않을 뿐이다).
   · 500원 단위로 정리한다(계산을 깔끔하게 하려는 것이고 규칙이 아니다). */
export const PER_MAX = 40000, PER_STEP = 500;
export function fixPer(v: number): number {
  return Math.min(PER_MAX, Math.max(0, Math.round(v / PER_STEP) * PER_STEP));
}

/* 밖에서 들어온 값(#q= 주소·엑셀 셀)을 "0 이상 정수"로 정리한다 — 입력칸에 사람이 직접 칠 때와
   같은 규칙. parseInt 는 값을 문자열로 바꿔 읽으므로 문자열이 아닌 것도 그대로 넘긴다. */
export const int0 = (x: unknown): number => Math.max(0, parseInt(x as string, 10) || 0);

